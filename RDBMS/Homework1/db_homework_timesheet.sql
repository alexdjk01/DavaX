-- SELECT care listeaza toti angajatii si pontarile lor daca exitsa
-- LEFT JOIN: include toti angajatii, chiar si cei fara pontaj daca sunt (coloanele lor vor fi null)
SELECT
    e.employeeID,
    e.firstName || ' ' || e.lastName AS employeeName,
    t.startDate,
    t.projectID,
    t.quantity
FROM employees e
LEFT JOIN timesheets t ON e.employeeID = t.employeeID
ORDER BY e.employeeID, t.startDate;

-- SELECT care compara media orelor lucrate zilnic cu valorile efective lucrate in fiecare zi
-- Pentru un dataset mare, nu este o functie utila deoarece returneaza foarte multe rezultate
/*Explicatie:
 ROUND(AVG(t.quantity) OVER (PARTITION BY t.employeeID), 2) AS avg_quantity_per_employee
        AVG -> calculeaza media valorilor din quantity
        OVER (PARTITION BY ...) -> calculeaza media separat pentru fiecare angajat, grupare pe employeeID
                                -> diferenta fara de groupBY : nu reduce randurile la o singura linie, pastreaza fiecare rand sia dauga o col calculata
        ROUND(..,2) -> rotunjeste rez la 2 zecimale
*/
SELECT
    t.timesheetID,
    e.firstName || ' ' || e.lastName AS employeeName,
    t.startDate,
    t.quantity,
    ROUND(AVG(t.quantity) OVER (PARTITION BY t.employeeID), 2) AS avg_quantity_per_employee  --f analitică: media orelor pe angajat
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
ORDER BY e.employeeID, t.startDate;


-- SELECT pentru clasificarea zilelor lucrate în functie de orele lucrate
 -- in functie de angajat, in ordine descrescatoare, cu atributul rank
 -- se poate astfel vedea zilele cu cele mai multe ore in ordine descrescatoare pentru fiecare angajat
SELECT
    e.firstName || ' ' || e.lastName AS employeeName,
    t.startDate,
    t.quantity,
    RANK() OVER (PARTITION BY t.employeeID ORDER BY t.quantity DESC) AS rank_by_quantity  --clasifica in func de nr de ore lucrate
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
ORDER BY employeeName, rank_by_quantity;

-- SELECT pt ore totale lucrate pe fiecare proiect, impartit pe tip de ore (Regular,ot etc.)
-- grupat dupa proiect si tipul de timp lucrat
SELECT
    p.projectName,
    tt.timeTypeName,
    SUM(t.quantity) AS total_hours
FROM timesheets t
JOIN projects p ON t.projectID = p.projectID
JOIN timeTypes tt ON t.timeTypeID = tt.timeTypeID
GROUP BY p.projectName, tt.timeTypeName
ORDER BY p.projectName, tt.timeTypeName;


