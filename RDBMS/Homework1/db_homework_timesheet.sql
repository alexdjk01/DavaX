/*
 ======== View creation area =========
 This area of the script is in charge with view creation
 !!!! Explicatii:
   View - tabel virtual care nu stocheaza date, doar defineste o interogare reutilizabila
   Materialized view - tip special de view care salveaza datele fizic in baza de date, ca o copie a unui select.
                      * este util deoarece se actualizeaza automat si poate interoga foarte rapid in cazul rapoartelor lente si costisitoare

    Am folosit Join, Group BY,SUM, LEFT JOIN
*/

-- materialized view - cate ore sunt lucrate te toti angajatii in functie de tipul de timp pontat.
CREATE MATERIALIZED VIEW mview_ore_timetypes
BUILD IMMEDIATE
REFRESH ON DEMAND
AS
SELECT 
    tt.timeTypeName,
    SUM(t.quantity) AS totalHours
FROM timesheets t
JOIN timeTypes tt ON t.timeTypeID = tt.timeTypeID
GROUP BY tt.timeTypeName;
COMMIT;

-- materialized view pentru a vedea totalul orelor lucrate pe saptaman per angajat, astfel obtinem o
-- imagine generala asupra volumului de munca depus de fiecare.
CREATE MATERIALIZED VIEW mview_lucru_saptamanal_anagajati
BUILD IMMEDIATE
REFRESH ON DEMAND
AS
SELECT
    e.employeeID,
    e.firstName || ' ' || e.lastName AS employeeName,
    TRUNC(t.startDate, 'IW') AS week_start_date,
    SUM(t.quantity) AS total_hours
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
GROUP BY e.employeeID, e.firstName, e.lastName, TRUNC(t.startDate, 'IW'); -- pentru a incepe saptamana luni, nu duminica
COMMIT;

--view -  cate ore a lucrat fiecare angajat pe proiect
CREATE OR REPLACE VIEW view_ore_per_angajat_per_proiect AS
SELECT 
    e.firstName || ' ' || e.lastName AS employeeName,
    p.projectName,
    SUM(t.quantity) AS totalHours
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
JOIN projects p ON t.projectID = p.projectID
GROUP BY e.firstName, e.lastName, p.projectName;
COMMIT;

-- view detaliat pe post de dashboard deoarece combina toate tabelele
CREATE OR REPLACE VIEW view_dashboard_detaliat AS
SELECT
    t.timesheetID,
    e.firstName || ' ' || e.lastName AS employeeName,
    p.projectName,
    tk.taskName,
    tt.timeTypeName,
    TO_CHAR(t.startDate, 'DD-MM-YYYY') AS workDay,
    t.startHour,
    t.endHour,
    t.quantity,
    l.locationName,
    c.countryName AS relocatedCountry,
    t.publicHolidayFlag,
    t.comments,
    t.extraInfo
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
JOIN projects p ON t.projectID = p.projectID
JOIN tasks tk ON t.taskID = tk.taskID
JOIN timeTypes tt ON t.timeTypeID = tt.timeTypeID
LEFT JOIN locations l ON t.locationID = l.locationID
LEFT JOIN countries c ON t.relocatedCountryID = c.countryID;
COMMIT;

-- view care arata orele suplimentare lucrate de fiecare angajat, grupate pe tip de ora suplimentara.
CREATE OR REPLACE VIEW view_anagjati_overtime AS
SELECT
    e.firstName || ' ' || e.lastName AS employeeName,
    tt.timeTypeName,
    SUM(t.quantity) AS overtimeHours
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
JOIN timeTypes tt ON t.timeTypeID = tt.timeTypeID
WHERE tt.timeTypeName IN ('Overtime', 'TOIL Overtime', 'Extended Overtime') -- permite numai cele de tip overtime
GROUP BY e.firstName, e.lastName, tt.timeTypeName;
COMMIT;

-- view care arata angajatii care au fost relocati sau au calatorit in scop de business
CREATE OR REPLACE VIEW view_angajati_relocati_businesTrip AS
SELECT
    e.firstName || ' ' || e.lastName AS employeeName,
    l.locationName AS travelLocation,
    c.countryName AS relocatedTo,
    t.startDate,
    t.projectID
FROM timesheets t
JOIN employees e ON t.employeeID = e.employeeID
LEFT JOIN locations l ON t.locationID = l.locationID
LEFT JOIN countries c ON t.relocatedCountryID = c.countryID
WHERE t.locationID IS NOT NULL OR t.relocatedCountryID IS NOT NULL;
COMMIT;


