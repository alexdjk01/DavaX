/*
 ======== Database creation area =========
 This area of the script is in charge with the database creation
 Constraints used:
    1. PK | 2. FK | 3. NOT NULL | 4. CHECK | 5. DEFAULT | 6. ALWAYS AS ... VIRTUAL| 7. CHECK pe JSON
    DEFAULT - daca valoarea nu este specificata la inserare, aceasta va fi default N (nu)
    ALWAYS - nu se poate seta valoarea manual
    VIRTUAL - valoarea este calculata la fiecare interogare si nu este stocata fizic
 !!!! Explicatii:
    1* as identity creaza o secventa interna si implicita,
        precum si un triger care este folosit atunci cand inserezi anumite randuri (nu mai trebuie facut manual)
    2* CLOB (Character large object) ne ajuta sa stocam texte foarte lungi (bun pentru fromat json)
*/
-- employees tabel creation:
CREATE TABLE employees (
    employeeID NUMBER GENERATED BY DEFAULT AS IDENTITY, -- explicatie 1*
    firstName VARCHAR2(50) NOT NULL,
    lastName VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) UNIQUE,
    workingLocation VARCHAR2(10) NOT NULL,
    companyRole VARCHAR2(50) NOT NULL,
    hireDate DATE DEFAULT SYSDATE,
    PRIMARY KEY (employeeID)
);
-- projects table creation:
CREATE TABLE projects (
    projectID VARCHAR2(20),
    projectName VARCHAR2(100) NOT NULL,
    clientName VARCHAR2(100) NOT NULL,
    PRIMARY KEY (projectID)
);
-- tasks table creation:
CREATE TABLE tasks (
    taskID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    taskName VARCHAR2(100) NOT NULL,
    PRIMARY KEY (taskID)
);
-- timetypes table creation: (timetypes sunt cele de genu :Regular, OT...)
CREATE TABLE timeTypes (
    timeTypeID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    timeTypeName VARCHAR2(50) UNIQUE NOT NULL,
    PRIMARY KEY (timeTypeID)
);
-- locations table creation:
CREATE TABLE locations (
    locationID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    locationName VARCHAR2(100) NOT NULL,
    PRIMARY KEY (locationID)
);
-- contry for relocation table creation:
CREATE TABLE countries (
    countryID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    countryName VARCHAR2(100) NOT NULL,
    PRIMARY KEY (countryID)
);
-- timesheets table creation:
-- This is the most important table!

CREATE TABLE timesheets (
    timesheetID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    employeeID NUMBER NOT NULL,
    projectID VARCHAR2(20) NOT NULL,
    taskID NUMBER NOT NULL,
    timeTypeID NUMBER NOT NULL,
    -- Datele calendaristice de start si sfarsit al pontajului
    startDate DATE NOT NULL,
    endDate DATE NOT NULL,
    -- ora de start si ora de finish al programului (in format 24h)
    startHour NUMBER(2) NOT NULL CHECK (startHour BETWEEN 0 AND 23), --Check constaing
    endHour NUMBER(2) NOT NULL CHECK (endHour BETWEEN 0 AND 23), --Check constraint 2
    -- cate ore au fost lucrate (generat automat ca diferenta dintre start-end)
    quantity NUMBER(4,2) GENERATED ALWAYS AS (endHour - startHour) VIRTUAL CHECK (quantity >= 0),
    -- campuri optionale (daca este cazul sunt completate, altfel null)
    locationID NUMBER,        -- pentru business trip
    relocatedCountryID NUMBER, -- pentru relocare (just in case)
    publicHolidayFlag CHAR(1) DEFAULT 'N' CHECK (publicHolidayFlag IN ('Y', 'N')), --daca se lucreaza in timpul unei sarbatori
    -- comentarii ale angajatilor in lecatura cu pontajul
    comments VARCHAR2(400),
    -- date semistructurate (JSON) : Aici putem stoca diferite date hidden (clientFeedback, toolsUsed, etc..)
    extraInfo CLOB CHECK (extraInfo IS JSON),   --2*
    --chei Pk si FK
    PRIMARY KEY (timesheetID),
    CONSTRAINT fk_employee FOREIGN KEY (employeeID) REFERENCES employees(employeeID),
    CONSTRAINT fk_project FOREIGN KEY (projectID) REFERENCES projects(projectID),
    CONSTRAINT fk_task FOREIGN KEY (taskID) REFERENCES tasks(taskID),
    CONSTRAINT fk_timeType FOREIGN KEY (timeTypeID) REFERENCES timeTypes(timeTypeID),
    CONSTRAINT fk_location FOREIGN KEY (locationID) REFERENCES locations(locationID),
    CONSTRAINT fk_country FOREIGN KEY (relocatedCountryID) REFERENCES countries(countryID)
);

